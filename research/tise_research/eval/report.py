"""Generate the benchmark report.

Every number in `docs/benchmarks/baselines.md` comes from here. Nothing is typed by hand,
which is the only way the file can be trusted after the tenth edit — a hand-maintained
benchmark table drifts from the code that produced it within a week, and the original
Tise documents shipped one that could never have been produced at all.

The report is written to be read by someone looking for the catch. Base rates sit next to
scores, the majority-class baseline is always present, categories below the label floor
are listed as unscored rather than omitted, and `unknown` gets its own section explaining
why it is not in the headline.
"""

from __future__ import annotations

from pathlib import Path

from tise_research.eval.backtest import EXCLUDED_FROM_HEADLINE, BacktestResult
from tise_research.reports import superseded_banner

__all__ = ["write_baseline_report"]


def _fmt(value: float | None, places: int = 4) -> str:
    return "n/a" if value is None else f"{value:.{places}f}"


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.1%}"


def _model_table(result: BacktestResult) -> str:
    rows = [
        "| Model | Brier | Log loss | Skill vs base rate | Test labels |",
        "|---|---:|---:|---:|---:|",
    ]
    for model in sorted(result.models.values(), key=lambda m: m.brier):
        skill = "reference" if model.name == "global_base_rate" else _fmt(model.skill, 3)
        note = " *" if model.name == "majority_class" else ""
        rows.append(
            f"| `{model.name}`{note} | {_fmt(model.brier)} | {_fmt(model.log_loss)} | "
            f"{skill} | {model.n:,} |"
        )
    return "\n".join(rows)


def _fold_table(result: BacktestResult) -> str:
    names = [name for name, _ in result.folds[0].brier] if result.folds else []
    header = "| Fold | Train | Test | Test ends | Base rate | " + " | ".join(
        f"`{name}`" for name in names
    ) + " |"
    divider = "|---:|---:|---:|---|---:|" + "---:|" * len(names)
    rows = [header, divider]
    for fold in result.folds:
        scores = dict(fold.brier)
        rows.append(
            f"| {fold.index} | {fold.train_size:,} | {fold.test_size:,} | "
            f"{fold.test_end:%Y-%m-%d} | {_pct(fold.base_rate)} | "
            + " | ".join(_fmt(scores.get(name), 3) for name in names)
            + " |"
        )
    return "\n".join(rows)


def _category_table(result: BacktestResult) -> str:
    rows = [
        "| Category | Test labels | Base rate | Best Brier | Best model |",
        "|---|---:|---:|---:|---|",
    ]
    entries = sorted(
        result.per_category.values(), key=lambda entry: (-entry.n, entry.subject)
    )
    for entry in entries:
        if entry.subject == EXCLUDED_FROM_HEADLINE:
            continue
        if entry.reported:
            rows.append(
                f"| {entry.subject} | {entry.n:,} | {_pct(entry.base_rate)} | "
                f"{_fmt(entry.brier)} | `{entry.best_model}` |"
            )
        else:
            rows.append(
                f"| {entry.subject} | {entry.n:,} | {_pct(entry.base_rate)} | "
                f"**not modelled** | — |"
            )
    return "\n".join(rows)


def _corpus_section(name: str, result: BacktestResult) -> str:
    unknown = result.per_category.get(EXCLUDED_FROM_HEADLINE)
    modelled = sum(1 for e in result.per_category.values() if e.reported)
    total_categories = len(result.per_category)

    unknown_text = (
        f"`unknown` holds **{result.unknown_label_count:,}** labels "
        f"({_pct(unknown.base_rate)} positive) and is **excluded from every number "
        "above**."
        if unknown
        else "No `unknown` labels in this corpus."
    )

    return f"""### {name}

{result.label_count:,} labels over
{result.span_start:%Y-%m-%d} to {result.span_end:%Y-%m-%d}, base rate
**{_pct(result.overall_base_rate)}**, {result.fold_count} folds.

{_model_table(result)}

`*` majority-class is a hard 0/1 predictor. Its log loss is the clamp
(`LOG_LOSS_EPSILON`) doing the work, not a measurement — see `eval/metrics.py`.

**Per fold** (Brier, lower is better):

{_fold_table(result)}

**Per category.** {modelled} of {total_categories} categories cleared the floor of
{result.min_category_labels} test labels; the rest are counted but not scored (D26).

{_category_table(result)}

{unknown_text}
"""


def write_baseline_report(
    results: dict[str, BacktestResult],
    *,
    out_dir: Path,
    timeout_seconds: float,
) -> Path:
    """Write `baselines.md`. Returns the path written."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "baselines.md"

    sections = "\n\n".join(
        _corpus_section(name, result) for name, result in sorted(results.items())
    )

    path.write_text(
        f"""# Baselines — `return_24h`

{superseded_banner("return_24h")}
Generated by `tise_research.eval.report`. **Do not edit by hand.** Regenerate with:

```
uv run python -m tise_research.eval.backtest
```

Session timeout {timeout_seconds:,.0f}s (D17), horizon 24h, one label per
(category, session) (D16). Corpora are measured **separately and never merged** (D18).

## How to read this

These are baselines. None of them learns anything, and that is the point: on this data
the base rate is around 70%, so a model must beat *reporting the base rate* before it has
demonstrated anything at all.

- **Brier** — mean squared error of the probability. Lower is better. 0.25 is
  uninformative.
- **Log loss** — punishes confident mistakes far harder. ln(2) ≈ 0.693 is uninformative.
- **Skill** — fractional improvement over `global_base_rate`. 0 means no better than
  reporting the base rate. This is the honest headline.
- **Accuracy is deliberately absent.** With a 70% base rate, always answering "yes"
  scores 70% and has learned nothing.

Folds are **rolling-origin and expanding**: fold *n* trains on everything before its
cutoff and tests on the chunk immediately after. Nothing is shuffled and there is no
random seed — two runs produce identical output.

Every baseline is fitted on its training window and then **frozen**. `same_as_last`
therefore repeats the last outcome seen *in training* across the whole test window rather
than updating as it goes. That is weaker than an online version, and it is said here
rather than quietly improved.

## `full` versus `history`

Not applicable to this table, and that is a real result rather than an omission. None of
these baselines uses dwell time — they see only the category and `window_end` — so the
`full` and `history` variants are **identical by construction**. Every number here is
achievable by the shipped extension.

It stayed that way at T10. D35 stopped Tise measuring dwell in either direction, so every
feature in `fs_2` is compat class `history` and the `full` class is empty (D51). The
distinction is kept because it is real, not because anything currently uses it.

{sections}

## Limitations

- **One person's browsing.** Every number describes the author. Nothing generalises, and
  no claim here should be read as a claim about people in general.
- **Frozen baselines.** See above; an online `same_as_last` would score better.
- **Small tails.** Most categories never clear the label floor. That is a fact about the
  data, not a tuning choice, and it will not improve much with more history because the
  distribution is dominated by a handful of domains.
- **`logreg_fs2` is not a baseline.** It appears in these tables because D24 requires the
  baselines beside it on identical folds, and this is where those folds are defined. What
  it means — where it clears the D28 bar, where it does not, and the per-fold picture the
  pooled score hides — is in `model.md`, and that is the file to read about it.
""",
        encoding="utf-8",
    )
    return path
